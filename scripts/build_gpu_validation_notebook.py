md(
    "## Section G -- GPU OOM / retry\n"
    "\n"
    "**Important honesty note (audit-fix pass, Finding 8):** every OOM in this section is a "
    "CONTROLLED, INJECTED trigger at a chosen batch size -- monkeypatching `cupy.asarray` to raise "
    "on request -- never a physical allocation large enough to actually exhaust the P100's VRAM. "
    "The exception raised is the REAL `cupy.cuda.memory.OutOfMemoryError` class (constructed "
    "directly, not a custom stand-in), so the real exception-type-matching path in "
    "`featm.gpu.dispatch._oom_exception_types()` is genuinely exercised -- but this is still an "
    "injected trigger, not hardware-confirmed physical OOM, and is reported as such."
)
code(
    "from featm.gpu import dispatch as gpu_dispatch\n"
    "\n"
    "_real_asarray = cupy.asarray\n"
    "_oom_state = {'above_rows': None, 'triggered': 0}\n"
    "\n"
    "def _make_real_oom_error(msg):\n"
    "    # Finding 8: construct the REAL CuPy OOM exception type directly (never a custom\n"
    "    # stand-in class), so the real exception-matching path in featm.gpu.dispatch.\n"
    "    # _oom_exception_types() is genuinely exercised. cupy.cuda.memory.OutOfMemoryError's\n"
    "    # __init__ signature is a private/version-specific implementation detail (it turned out\n"
    "    # to require positional (size, total, limit)-style args on this CuPy version, not a\n"
    "    # plain message string) -- constructed defensively across a few call shapes rather than\n"
    "    # hardcoding one signature that could break on a different CuPy version.\n"
    "    exc_type = cupy.cuda.memory.OutOfMemoryError\n"
    "    for args in ((msg,), (0, 0, 0), (0, 0)):\n"
    "        try:\n"
    "            return exc_type(*args)\n"
    "        except TypeError:\n"
    "            continue\n"
    "    exc = exc_type.__new__(exc_type)\n"
    "    Exception.__init__(exc, msg)\n"
    "    return exc\n"
    "\n"
    "def _oom_asarray(a, dtype=None):\n"
    "    arr = _real_asarray(a, dtype=dtype)\n"
    "    if _oom_state['above_rows'] is not None and arr.ndim >= 1 and arr.shape[0] > _oom_state['above_rows']:\n"
    "        _oom_state['triggered'] += 1\n"
    "        raise _make_real_oom_error(f\"injected OOM: {arr.shape[0]} rows > {_oom_state['above_rows']}\")\n"
    "    return arr\n"
    "\n"
    "cupy.asarray = _oom_asarray\n"
)
