    "# within the measured range, fall back to just past the largest measured point (never silently\n"
    "# assume GPU wins beyond what was actually measured).\n"
    "def _derive_threshold_elements(points):\n"
    "    pts = sorted(points)  # [(elements, speedup), ...]\n"
    "    for i in range(len(pts)):\n"
    "        elements_i, speedup_i = pts[i]\n"
    "        if speedup_i < REQUIRED_AUTO_SPEEDUP:\n"
    "            continue\n"
    "        if i + 1 < len(pts):\n"
    "            elements_next, speedup_next = pts[i + 1]\n"
    "            if speedup_next >= REQUIRED_AUTO_SPEEDUP:\n"
    "                return elements_i\n"
    "            continue  # this point alone is not enough evidence -- keep looking\n"
    "        return elements_i  # last measured point already clears the bar with nothing further to confirm against\n"
